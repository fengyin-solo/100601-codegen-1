// 品名命中规则：任一关键词出现在品名里即算命中，先登记者优先。
export function matchRule(goodsName: string): DgRule | null {
  const name = goodsName.trim()
  if (!name) {
    return null
  }
  for (const rule of DG_RULES) {
    if (rule.品名关键词.some((keyword) => name.includes(keyword))) {
      return rule
    }
  }
  return null
}
